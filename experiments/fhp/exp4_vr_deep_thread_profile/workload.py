"""Explicit scratch fixtures and workload checks, isolated from production code.

Only load fixtures generated by this process: torch.load(weights_only=False)
is necessary for Python/NumPy RNG state and must not read untrusted files.
"""

from contextlib import contextmanager
from copy import deepcopy
import hashlib
import json
import random
import time

import numpy as np
import torch

from experiments.fhp.exp2_vr_deep_lossless_24h.train import make_solver
from fhp_vr_deep.io_utils import peak_rss_mib

MODEL_NAMES = ("model", "target_model", "imm_model", "best_model")
OPTIMIZER_NAMES = ("optimizer", "imm_optimizer")


def trainers(solver):
    return dict(regret_0=solver.regret_trainers[0], regret_1=solver.regret_trainers[1],
                critic=solver.q_value_trainer, policy=solver.ave_policy_trainer)


def new_solver(spec):
    solver = make_solver(spec["source_seed"], spec["training_config"])
    solver.logger._verbose = False
    assert solver.evaluation_frequency == 0
    assert not solver.training_time_checkpoint_seconds
    return solver


def rng_state():
    return dict(python=random.getstate(), numpy=np.random.get_state(), torch=torch.get_rng_state())


def restore_rng(state):
    random.setstate(state["python"])
    np.random.set_state(state["numpy"])
    torch.set_rng_state(state["torch"])


def clear_features(solver):
    solver.feature_encoder._information_cache.clear()
    solver.feature_encoder._full_state_cache.clear()


def model_state(solver):
    return {name: {key: deepcopy(getattr(trainer, key).state_dict())
                   for key in (*MODEL_NAMES, *OPTIMIZER_NAMES) if hasattr(trainer, key)}
            for name, trainer in trainers(solver).items()}


def buffer_state(buffer):
    size = min(len(buffer), buffer.buffer_size)
    # Never serialise uninitialised array tails. Keep physical circular order.
    arrays = {key: value[:size].copy() for key, value in vars(buffer).items()
              if isinstance(value, np.ndarray)}
    counters = {key: getattr(buffer, key) for key in ("cur_id", "size") if hasattr(buffer, key)}
    return dict(arrays=arrays, counters=counters, populated_rows=size, capacity=buffer.buffer_size)


def replay_digest(solver):
    """Numerical replay verification outside timing, without copying GB arrays."""
    digest = hashlib.sha256()
    for name, trainer in trainers(solver).items():
        buffer = trainer.buffer
        size = min(len(buffer), buffer.buffer_size)
        digest.update(json.dumps([name, size, buffer.cur_id]).encode())
        for key, value in sorted(vars(buffer).items()):
            if isinstance(value, np.ndarray):
                digest.update(json.dumps([key, value.dtype.str, list(value[:size].shape)]).encode())
                digest.update(memoryview(value[:size]).cast("B"))
    return digest.hexdigest()


def save_fixture(path, solver, buffers):
    payload = dict(models=model_state(solver), rng=rng_state(),
                   counters={key: getattr(solver, key) for key in ("num_iteration", "episode", "nodes_touched")},
                   pending=deepcopy(solver.logger._pending),
                   buffers={name: buffer_state(trainers(solver)[name].buffer) for name in buffers})
    torch.save(payload, path)
    return {name: dict(populated_rows=value["populated_rows"], capacity=value["capacity"],
                       counters=value["counters"])
            for name, value in payload["buffers"].items()}


def load_fixture(path, spec):
    payload = torch.load(path, map_location="cpu", weights_only=False)
    solver = new_solver(spec)
    for name, states in payload["models"].items():
        trainer = trainers(solver)[name]
        for key, state in states.items():
            if not hasattr(trainer, key):
                assert key == "best_model"
                setattr(trainer, key, trainer.init_model())
            getattr(trainer, key).load_state_dict(state)
    for name, data in payload["buffers"].items():
        buffer = trainers(solver)[name].buffer
        assert buffer.buffer_size == data["capacity"]
        for key, array in data["arrays"].items():
            getattr(buffer, key)[:data["populated_rows"]] = array
        for key, value in data["counters"].items():
            setattr(buffer, key, value)
    for key, value in payload["counters"].items():
        setattr(solver, key, value)
    solver.logger._pending = payload["pending"]
    clear_features(solver)
    restore_rng(payload["rng"])
    return solver


class BatchDigest:
    """Hash ordered sampler calls, populations and indices, without retaining them."""

    def __init__(self):
        self.digest = hashlib.sha256()
        self.calls = 0

    @contextmanager
    def observe(self, solver):
        originals = []
        try:
            for name, trainer in trainers(solver).items():
                buffer = trainer.buffer
                original = buffer.sample_indices
                originals.append((buffer, original, "sample_indices" in vars(buffer)))

                def sample(num_samples=-1, *, _fn=original, _buffer=buffer, _name=name):
                    indices = _fn(num_samples)
                    count = min(len(_buffer), _buffer.buffer_size)
                    self.digest.update(json.dumps([_name, num_samples, count]).encode())
                    if isinstance(indices, slice):
                        self.digest.update(repr(indices).encode())
                    else:
                        self.digest.update(np.asarray(indices, dtype="<i8").tobytes())
                    self.calls += 1
                    return indices

                buffer.sample_indices = sample
            yield self
        finally:
            for buffer, original, overridden in originals:
                # Remove the profiling closure, including its reference cycle.
                if overridden:
                    buffer.sample_indices = original
                else:
                    del buffer.sample_indices

    def result(self):
        return dict(sha256=self.digest.hexdigest(), calls=self.calls)


class ChoiceTrace:
    """Keep game paths fixed, while consuming the normal NumPy random draws.

    This is a timing workload, NOT a valid independently trained strategy.
    Numerical drift can change candidate actions; count it and report it.
    """

    def __init__(self, events=None):
        self.events = [] if events is None else events
        self.recording = events is None
        self.cursor = self.divergences = 0

    @contextmanager
    def observe(self):
        original = np.random.choice

        def choice(a, size=None, replace=True, p=None):
            if size is not None:
                raise ValueError("Unexpected vector choice in traversal")
            natural = original(a, size=size, replace=replace, p=p)
            population = int(a) if np.isscalar(a) else len(a)
            if self.recording:
                event = (population, int(natural))
                self.events.append(event)
            else:
                if self.cursor >= len(self.events):
                    raise ValueError("Traversal exceeded reference trace")
                event = self.events[self.cursor]
                if event[0] != population:
                    raise ValueError("Traversal choice population changed")
            self.cursor += 1
            self.divergences += int(natural != event[1])
            return event[1]

        np.random.choice = choice
        try:
            yield self
            if self.cursor != len(self.events):
                raise ValueError("Traversal did not consume complete reference trace")
        finally:
            np.random.choice = original


class InferenceTrace:
    """Execute real inference but replay reference outputs for controlled data.

    Substituting only actions could select a zero-probability opponent action
    after a thread-dependent policy update. Replaying collection outputs as well
    keeps importance denominators and the numerical replay data identical. This
    hook is exclusively for profiling: never use it to produce a trained policy.
    """

    def __init__(self, events=None):
        self.events = [] if events is None else events
        self.recording = events is None
        self.cursor = self.different_outputs = 0
        self.max_abs_difference = 0.0

    @contextmanager
    def observe(self, solver):
        hooks = [(f"policy_{p}", trainer, "get_policy") for p, trainer in enumerate(solver.regret_trainers)]
        hooks.append(("critic", solver.q_value_trainer, "get_baseline"))
        originals = []
        try:
            for name, trainer, method in hooks:
                original = getattr(trainer, method)
                originals.append((trainer, method, original, method in vars(trainer)))

                def infer(*args, _fn=original, _name=name, **kwargs):
                    actual = np.asarray(_fn(*args, **kwargs))
                    if not np.isfinite(actual).all():
                        raise ValueError(f"Non-finite collection inference: {_name}")
                    if self.recording:
                        event = (_name, actual.dtype.str, actual.tolist())
                        self.events.append(event)
                    else:
                        if self.cursor >= len(self.events):
                            raise ValueError("Inference exceeded reference trace")
                        event = self.events[self.cursor]
                        if event[0] != _name:
                            raise ValueError("Inference call order differs from reference")
                    expected = np.asarray(event[2], dtype=event[1])
                    if expected.shape != actual.shape:
                        raise ValueError("Inference shape differs from reference")
                    self.cursor += 1
                    self.different_outputs += int(not np.array_equal(expected, actual))
                    self.max_abs_difference = max(self.max_abs_difference, float(np.max(np.abs(actual - expected))))
                    # dfs mutates critic outputs in place; never return trace storage.
                    return expected.copy()

                setattr(trainer, method, infer)
            yield self
            if self.cursor != len(self.events):
                raise ValueError("Inference did not consume complete reference trace")
        finally:
            for trainer, method, original, overridden in originals:
                if overridden:
                    setattr(trainer, method, original)
                else:
                    delattr(trainer, method)


def endpoint(solver):
    return {f"{name}.{model}.{key}": value.detach().cpu().clone()
            for name, trainer in trainers(solver).items() for model in MODEL_NAMES
            if hasattr(trainer, model)
            for key, value in getattr(trainer, model).state_dict().items()}


def endpoint_difference(solver, reference):
    actual = endpoint(solver)
    if actual.keys() != reference.keys():
        raise ValueError("Different endpoint architecture")
    max_abs = 0.0
    for name, value in actual.items():
        if not torch.isfinite(value).all():
            raise ValueError(f"Non-finite model: {name}")
        max_abs = max(max_abs, (value - reference[name]).abs().max().item())
    return max_abs


def measure(solver, fn):
    solver.phase_seconds = {}
    before_nodes = solver.nodes_touched
    before_episode, before_iteration = solver.episode, solver.num_iteration
    sampler = BatchDigest()
    with sampler.observe(solver):
        cpu_start, start = time.process_time(), time.perf_counter()
        fn()
        seconds, cpu = time.perf_counter() - start, time.process_time() - cpu_start
    return dict(seconds=seconds, cpu_seconds=cpu, average_busy_cores=cpu / seconds,
                phase_seconds=dict(solver.phase_seconds), sampler=sampler.result(),
                nodes=solver.nodes_touched - before_nodes,
                traversals=solver.episode - before_episode, iterations=solver.num_iteration - before_iteration,
                peak_rss_mib=peak_rss_mib())


def kernel_warmup(spec):
    """Unmeasured BLAS/Adam warm-up on disposable models, before fixture restore."""
    solver = new_solver(spec)
    for trainer in trainers(solver).values():
        x = torch.zeros((trainer.batch_size, trainer.input_size), dtype=torch.float32)
        for _ in range(3):
            trainer.optimizer.zero_grad()
            trainer.model(x).square().mean().backward()
            trainer.optimizer.step()


def fit_call(solver, component):
    if component == "policy":
        return solver.train_average_policy
    player = int(component[-1])
    return (lambda: solver.train_regret(player)) if component.startswith("regret") else (
        lambda: solver.train_baseline(player))
